"""Transparent wrapper around a real Cognee hook command (stdlib only).

Claude Code calls:  python tee_hook.py <index>
The wrapper runs the real hook command (from $CTB_HOOKS_FILE, generated by the harness) with
the same stdin, passes stdout / stderr / exit code through UNCHANGED, and appends whatever
the hook injected into Claude's context to $CTB_COGNEE_HOOK_LOG.

Nothing is added to Claude's context. The Cognee plugin needs no changes.

What counts as "injected into the context" (Claude Code hook semantics):
  - plain stdout of UserPromptSubmit / SessionStart hooks
  - JSON stdout with hookSpecificOutput.additionalContext (any event)
  - stderr when the hook exits with code 2 (fed back to Claude)
"""
import json
import os
import subprocess
import sys
import time

PLAIN_STDOUT_EVENTS = {"UserPromptSubmit", "SessionStart"}


def injected_texts(stdout, stderr, returncode, event):
    if returncode == 2:
        return [stderr.strip()] if stderr.strip() else []
    if returncode != 0:
        return []
    s = stdout.strip()
    if not s:
        return []
    try:
        j = json.loads(s)
    except json.JSONDecodeError:
        return [s] if event in PLAIN_STDOUT_EVENTS else []
    if isinstance(j, dict):
        ctx = (j.get("hookSpecificOutput") or {}).get("additionalContext")
        return [ctx.strip()] if isinstance(ctx, str) and ctx.strip() else []
    return []


def main():
    idx = int(sys.argv[1])
    with open(os.environ["CTB_HOOKS_FILE"]) as fh:
        hook = json.load(fh)[idx]
    stdin = sys.stdin.buffer.read()
    p = subprocess.run(hook["command"], shell=True, input=stdin, capture_output=True)
    sys.stdout.buffer.write(p.stdout)
    sys.stderr.buffer.write(p.stderr)
    sys.stdout.flush()
    log = os.environ.get("CTB_COGNEE_HOOK_LOG")
    if log:
        texts = injected_texts(p.stdout.decode("utf-8", "replace"), p.stderr.decode("utf-8", "replace"),
                               p.returncode, hook["event"])
        with open(log, "a") as fh:
            for t in texts:
                fh.write(json.dumps({"ts": time.time(), "event": hook["event"], "text": t}) + "\n")
    sys.exit(p.returncode)


if __name__ == "__main__":
    main()
